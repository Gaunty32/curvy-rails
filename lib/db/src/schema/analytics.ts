import { pgTable, uuid, text, timestamp, boolean, numeric, integer, index, uniqueIndex } from "drizzle-orm/pg-core";

export const analyticsSessionsTable = pgTable("analytics_sessions", {
  sessionId: uuid("session_id").primaryKey(),
  visitorId: uuid("visitor_id").notNull(),
  firstTouch: text("first_touch").notNull(),
  firstPath: text("first_path").notNull(),
  referrerDomain: text("referrer_domain"),
  utmSource: text("utm_source"), utmMedium: text("utm_medium"), utmCampaign: text("utm_campaign"),
  utmContent: text("utm_content"), utmTerm: text("utm_term"),
  channel: text("channel").notNull(),
  deviceCategory: text("device_category").notNull(),
  firstSeenAt: timestamp("first_seen_at", { withTimezone: true }).notNull().defaultNow(),
  lastSeenAt: timestamp("last_seen_at", { withTimezone: true }).notNull().defaultNow(),
}, (t) => ({
  visitorIdx: index("analytics_sessions_visitor_idx").on(t.visitorId),
}));
export const analyticsEventsTable = pgTable("analytics_events", {
  id: integer("id").generatedAlwaysAsIdentity().primaryKey(),
  eventId: uuid("event_id").notNull().unique(),
  visitorId: uuid("visitor_id").notNull(),
  sessionId: uuid("session_id").notNull(),
  eventType: text("event_type").notNull(),
  occurredAt: timestamp("occurred_at", { withTimezone: true }).notNull(),
  path: text("path").notNull(),
  productId: text("product_id"),
  categoryId: text("category_id"),
  channel: text("channel").notNull(),
  landingPath: text("landing_path").notNull(),
  referrerDomain: text("referrer_domain"),
  deviceCategory: text("device_category").notNull(),
  searchTerm: text("search_term"),
  quantity: integer("quantity"),
  value: numeric("value", { precision: 12, scale: 2 }),
}, (t) => ({
  dateIdx: index("analytics_events_date_idx").on(t.occurredAt),
  sessionIdx: index("analytics_events_session_idx").on(t.sessionId),
  typeIdx: index("analytics_events_type_idx").on(t.eventType),
  productIdx: index("analytics_events_product_idx").on(t.productId),
  categoryIdx: index("analytics_events_category_idx").on(t.categoryId),
  channelIdx: index("analytics_events_channel_idx").on(t.channel),
}));
export const orderAttributionTable = pgTable("order_attribution", {
  orderId: integer("order_id").primaryKey(),
  visitorId: uuid("visitor_id"),
  sessionId: uuid("session_id"),
  firstTouch: text("first_touch").notNull(),
  lastTouch: text("last_touch").notNull(),
  firstLandingPath: text("first_landing_path").notNull(),
  lastLandingPath: text("last_landing_path").notNull(),
  firstChannel: text("first_channel").notNull(),
  lastChannel: text("last_channel").notNull(),
  firstReferrerDomain: text("first_referrer_domain"),
  lastReferrerDomain: text("last_referrer_domain"),
  firstUtmSource: text("first_utm_source"), firstUtmMedium: text("first_utm_medium"),
  firstUtmCampaign: text("first_utm_campaign"), firstUtmContent: text("first_utm_content"), firstUtmTerm: text("first_utm_term"),
  lastUtmSource: text("last_utm_source"), lastUtmMedium: text("last_utm_medium"),
  lastUtmCampaign: text("last_utm_campaign"), lastUtmContent: text("last_utm_content"), lastUtmTerm: text("last_utm_term"),
  repeatOrder: boolean("repeat_order").notNull().default(false),
  revenue: numeric("revenue", { precision: 12, scale: 2 }).notNull().default("0"),
  createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
});